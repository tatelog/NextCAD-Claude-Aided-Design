// 仕様（統括の依頼 2026-11-06。2: 地名地番）。筆の属性から「江東区新砂二丁目625番1」の形を作る:
// CH1: 市区町村名・大字名・丁目名（全角の数字は漢数字）・地番（「-」は「番」）をつなぐ。
// CH2: 枝番が無いときは「100番」（「番」だけ）。
// CH3: 丁目名が無いときは丁目を省く。
// CH4: 地番が無いときは null（地名地番は書けない）。
// CH5: 10 丁目以上も漢数字（十・十一・二十）にする。
import { describe, expect, it } from 'vitest'
import { chibanOf } from './parcelInfo'

const P = { 市区町村名: '江東区', 大字名: '新砂', 丁目名: '２丁目', 地番: '625-1' }

describe('地名地番（仕様 CH1〜CH5）', () => {
  it('CH1: 区名・大字・丁目（漢数字）・地番（- は番）をつなぐ', () => {
    expect(chibanOf(P)).toBe('江東区新砂二丁目625番1')
  })

  it('CH2: 枝番が無いときは「100番」', () => {
    expect(chibanOf({ ...P, 地番: '100' })).toBe('江東区新砂二丁目100番')
  })

  it('CH3: 丁目名が無いときは丁目を省く', () => {
    expect(chibanOf({ ...P, 丁目名: null })).toBe('江東区新砂625番1')
  })

  it('CH4: 地番が無ければ null', () => {
    expect(chibanOf({ ...P, 地番: null })).toBeNull()
    expect(chibanOf({ 市区町村名: '江東区', 大字名: '新砂' })).toBeNull()
  })

  it('CH5: 10 丁目以上は十・十一・二十（漢数字）', () => {
    expect(chibanOf({ ...P, 丁目名: '１０丁目' })).toBe('江東区新砂十丁目625番1')
    expect(chibanOf({ ...P, 丁目名: '１１丁目' })).toBe('江東区新砂十一丁目625番1')
    expect(chibanOf({ ...P, 丁目名: '２０丁目' })).toBe('江東区新砂二十丁目625番1')
  })
})
