// 仕様（統括の依頼 2026-11-06。2-a: 取り込んだ Word が、どの様式かを見分ける）:
// K1: 第二号様式（確認申請書（建築物））の見出しで、F2 と分かる。
// K2: 第三号様式（建築計画概要書。字間に空白があっても）で、F3 と分かる。
// K3: 第八号様式の「昇降機以外の建築設備」で、F8E と分かる（調査の ID に合わせた）。
// K4: 第八号様式の「昇降機」で、F8 と分かる。
// K5: どれでもなければ null（「どの様式か分からない」と出す）。
import { describe, expect, it } from 'vitest'
import { formKindOf } from './permitFormKind'

const F2 = ['第二号様式（第一条の三、第三条、第三条の三関係）（Ａ４）', '確認申請書（建築物）', '（第一面）']
const F3 = ['第三号様式（第一条の三、第三条、第三条の三、第三条の四関係）（Ａ４）', '建 築 計 画 概 要 書（第一面）', '建築主等の概要']
const F8O = ['第八号様式（第一条の三、第二条の二、第三条の三関係）（昇降機以外の建築設備用）（Ａ４）', '確認申請書（昇降機以外の建築設備）', '（第一面）']
const F8E = ['第八号様式（第一条の三、第二条の二、第三条の三関係）（昇降機用）（Ａ４）', '確認申請書（昇降機）', '（第一面）']

describe('様式の見分け（仕様 K1〜K5）', () => {
  it('K1: 第二号様式は F2', () => {
    expect(formKindOf(F2)).toBe('F2')
  })

  it('K2: 第三号様式は F3（字間の空白を無視する）', () => {
    expect(formKindOf(F3)).toBe('F3')
  })

  it('K3: 第八号様式の昇降機以外は F8E', () => {
    expect(formKindOf(F8O)).toBe('F8E')
  })

  it('K4: 第八号様式の昇降機は F8', () => {
    expect(formKindOf(F8E)).toBe('F8')
  })

  it('K5: どれでもなければ null', () => {
    expect(formKindOf(['確認申請書（その他）', '（第一面）'])).toBeNull()
    expect(formKindOf([])).toBeNull()
  })
})
