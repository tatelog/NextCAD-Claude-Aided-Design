// 仕様（ハブ A-03 G28・D-02 C11。出典: 法 61 条 1 項を e-Gov 法令 API で 2026-11-04 に確認。数値条件（階数・延べ面積）は政令に委ねられ、ここでは確かめていない）。
// 統括の判断（2026-11-05、案 B）: 判定の中身は変えず、文に「どの区域か」と「何が未確認で判定不能か」を添える。
// 防火地域・準防火地域の法規は、地点に当たる地域の区分から、判定の結果を決める。数値条件が未確認のものは「判定不能」と出し、推測で埋めない。
// 仕様 1: 地点に防火地域（区分 24）があれば、「法 61 条 1 項: 防火地域。数値条件（階数・延べ面積）は政令・告示の基準が未確認のため判定不能」。
// 仕様 2: 地点に準防火地域（区分 25）だけがあれば、「法 61 条 1 項: 準防火地域。数値条件（階数・延べ面積）は政令・告示の基準が未確認のため判定不能」。
// 仕様 3: 地点に防火・準防火の地域が無ければ、「法 61 条 1 項: 指定なし。61 条の対象外」。
// 仕様 4: 区分が不明（未取得・知らないコード）の地域があれば、「判定不能（区分が未取得）」。区分が 24・25 の地域と混じっても、不明を優先して出す。
// 仕様 5: 防火と準防火が両方（区域が重なる）なら、どちらとも決めず「判定不能（防火地域と準防火地域が重なる。元データの確認が要る）」。
// 仕様 6: 入力を書き換えず、同じ入力には同じ出力。
import { describe, expect, it } from 'vitest'
import { fireDecisionLine } from './fireZone'

const UNDETERMINED = '数値条件（階数・延べ面積）は政令・告示の基準が未確認のため判定不能'

describe('防火・準防火地域の判定の文（仕様 1〜6）', () => {
  it('仕様 1: 防火地域（24）があれば、「防火地域。」から始める', () => {
    expect(fireDecisionLine([{ function: 24 }])).toBe(`法 61 条 1 項: 防火地域。${UNDETERMINED}`)
  })

  it('仕様 2: 準防火地域（25）だけなら、「準防火地域。」から始める', () => {
    expect(fireDecisionLine([{ function: 25 }])).toBe(`法 61 条 1 項: 準防火地域。${UNDETERMINED}`)
  })

  it('仕様 3: 地域が無ければ「指定なし。61 条の対象外」', () => {
    expect(fireDecisionLine([])).toBe('法 61 条 1 項: 指定なし。61 条の対象外')
  })

  it('仕様 4: 区分が不明の地域があれば、区分が未取得として判定不能（混じっても不明を優先）', () => {
    expect(fireDecisionLine([{ function: null }])).toBe('法 61 条 1 項: 判定不能（区分が未取得）')
    expect(fireDecisionLine([{ function: 24 }, { function: 99 }])).toBe('法 61 条 1 項: 判定不能（区分が未取得）')
  })

  it('仕様 5: 防火と準防火が両方あれば、どちらとも決めず、重なりとして判定不能', () => {
    expect(fireDecisionLine([{ function: 24 }, { function: 25 }])).toBe(
      '法 61 条 1 項: 判定不能（防火地域と準防火地域が重なる。元データの確認が要る）',
    )
  })

  it('仕様 6: 同じ入力には同じ出力で、入力を書き換えない', () => {
    const input = [{ function: 24 as number | null }]
    expect(fireDecisionLine(input)).toBe(fireDecisionLine(input))
    expect(input).toEqual([{ function: 24 }])
  })
})
