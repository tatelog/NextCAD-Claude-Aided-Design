// 仕様: 経緯度から 2 次メッシュ番号を求める（日本の標準地域メッシュ。PLATEAU の API の mm: の番号と同じ）。
// 仕様 1: 1 次メッシュ（4 桁）は、緯度 × 1.5 の整数部（2 桁）と 経度 − 100 の整数部（2 桁）。
// 仕様 2: 2 次メッシュ（6 桁）は、1 次の後ろに、緯度の 1 次メッシュ内の位置（× 8 の整数部）と経度の位置（× 8 の整数部）を 1 桁ずつ続ける。
// 仕様 3: 日本の範囲（緯度 20〜46、経度 122〜154）の外は弾く。
// 確認: 江東区のメッシュ 533946 の範囲に入る点（東京駅付近、35.6812N 139.7671E）は 533946 になる。
import { describe, expect, it } from 'vitest'
import { meshCode2nd } from './mesh'

describe('meshCode2nd（2 次メッシュ）', () => {
  it('東京駅付近は 533946', () => {
    expect(meshCode2nd({ lat: 35.6812, lon: 139.7671 })).toBe('533946')
  })

  it('境界の内側の別の点', () => {
    // 35.6667（緯度 53.5 の境）の少し北、139.75 の少し東: 533946
    expect(meshCode2nd({ lat: 35.67, lon: 139.76 })).toBe('533946')
  })

  it('日本の範囲の外は弾く', () => {
    expect(() => meshCode2nd({ lat: 10, lon: 139 })).toThrow()
    expect(() => meshCode2nd({ lat: 35, lon: 170 })).toThrow()
  })
})
